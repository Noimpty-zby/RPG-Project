std::string affixPage() {
  std::string text;
  for (int id = 0; id < AffixCount; ++id) {
    const Affix affix = static_cast<Affix>(id);
    text += std::string("· [") + affixName(affix) + "] " + affixDescription(affix) + "\n";
  }
  text += "· 敌人可能同时带有多个词缀，楼层越高越常见；击败带词缀的敌人奖励更多。";
  return text;
}

