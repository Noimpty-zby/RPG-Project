namespace Help {
int topicCount() { return count; }
const char *topicTitle(int topic) {
  return topic >= 1 && topic <= count ? topics[topic - 1].title : "";
}
std::string topicText(int topic) {
  if (topic < 1 || topic > count) return "";
  const Topic &page = topics[topic - 1];
  return page.build ? page.build() : page.text;
}
} // namespace Help
